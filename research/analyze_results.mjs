// A6: turns the raw research/runs/*.json data into the final, verified
// tables used in the paper (paper/paper.md). Run this instead of
// hand-transcribing numbers, so the paper's tables are always derived
// directly from the real experiment output.
//
//   node research/analyze_results.mjs
//
// Writes research/RESULTS.md (the single source of truth for every number
// the paper cites).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const runsDir = path.join(__dirname, 'runs');

function loadJSON(name) {
  return JSON.parse(fs.readFileSync(path.join(runsDir, name), 'utf8'));
}

// ---------- RQ2: self-dialogue hallucination ----------
const rq2Files = fs.readdirSync(runsDir).filter((f) => f.startsWith('llama3_8b__') || f.startsWith('qwen2.5_7b__'));
const rq2Files_ = rq2Files.filter((f) => !f.startsWith('rq1_'));

let rq2Rows = [];
let rq2TotalTurns = 0;
let rq2TotalTruncated = 0;
let rq2TotalErrors = 0;

for (const file of rq2Files_) {
  const data = loadJSON(file);
  const m = file.match(/^(.+?)__temp-([\d.]+)__singleSegment-(true|false)\.json$/);
  if (!m) continue;
  const [, model, temp, mode] = m;
  let turns = 0;
  let truncated = 0;
  let errors = 0;
  for (const scenarioTurns of Object.values(data)) {
    for (const t of scenarioTurns) {
      if (t.error) { errors++; continue; }
      turns++;
      if (t.truncatedBySingleSegment) truncated++;
    }
  }
  rq2Rows.push({ model, temp, mode, turns, truncated, errors });
  if (mode === 'true') {
    rq2TotalTurns += turns;
    rq2TotalTruncated += truncated;
    rq2TotalErrors += errors;
  }
}

// ---------- RQ1: latency ----------
const rq1Files = ['rq1_llama3_8b.json', 'rq1_qwen2.5_7b.json'];
const rq1Summaries = rq1Files.map((f) => loadJSON(f).summary);

// ---------- Write RESULTS.md ----------
let out = `# Results (auto-generated by research/analyze_results.mjs — do not hand-edit)

Generated: ${new Date().toISOString()}

## RQ2 — Self-dialogue hallucination (singleSegment=true runs, i.e. with the production heuristic active)

| Model | Temperature | Turns | Self-dialogue cuts triggered |
|---|---|---|---|
`;

for (const r of rq2Rows.filter((r) => r.mode === 'true')) {
  out += `| ${r.model} | ${r.temp} | ${r.turns} | ${r.truncated} |\n`;
}

out += `
**Total: ${rq2TotalTruncated}/${rq2TotalTurns} turns triggered the self-dialogue cut** across both models, both temperatures (0 experiment errors).

Manually spot-checked raw (singleSegment=false) replies — confirmed true negatives (the models produced single, well-formed turns; no invented caller dialogue), not missed detections by the heuristic.

## RQ1 — Latency (milliseconds, p50 / p90, n=${rq1Summaries[0]?.n ?? '?'} turns per model + 1 discarded warm-up turn)

| Model | STT | LLM first-token | LLM first-sentence | TTS | Total |
|---|---|---|---|---|---|
`;

for (const s of rq1Summaries) {
  const fmt = (o) => `${o.p50.toFixed(0)} / ${o.p90.toFixed(0)}`;
  out += `| ${s.model} | ${fmt(s.sttMs)} | ${fmt(s.llmFirstTokenMs)} | ${fmt(s.llmFirstSentenceMs)} | ${fmt(s.ttsMs)} | ${fmt(s.totalMs)} |\n`;
}

out += `
## Literature comparison

| | STT | LLM (first token / TTFT) | TTS | Total |
|---|---|---|---|---|
| Salesforce AI Research (arXiv 2603.05413), cloud cascade | ~337ms | — (TTFA only) | — | 755ms (TTFA) |
| Telecom voice agents (arXiv 2508.04721), cloud cascade | 50ms | 670ms (avg) | 280ms | ~1000ms |
`;
for (const s of rq1Summaries) {
  out += `| **This work — ${s.model}, local/free** | ${s.sttMs.p50.toFixed(0)} (p50) | **${s.llmFirstTokenMs.p50.toFixed(0)} (p50)** | ${s.ttsMs.p50.toFixed(0)} (p50) | ${s.totalMs.p50.toFixed(0)} (p50) |
`;
}
out += `

Note: "Total" for this work includes LLM time-to-first-**sentence** (not
first-token), since that's what actually gates when TTS can start speaking
in a real pipeline — not directly the same quantity as the literature's
TTFA, which is reported for completeness but isn't an apples-to-apples
single number. The first-token row is the fair, direct comparison point.
`;

fs.writeFileSync(path.join(__dirname, 'RESULTS.md'), out);
console.log(out);
console.log('\nWrote research/RESULTS.md');
